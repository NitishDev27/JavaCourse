public class conditional1 {
   public static void main(String[] args) {
     // Switch statement

     int i = 4;
    // switch (expression)--> byte, short, int char, Enumeration
    switch (i) {
         case 1:
             System.out.println("i is 1");
             break;
         case 2:
            System.out.println("i is 2");
            break;
         case 3:
            System.out.println("i is 3");
            break;
         case 4:
            System.out.println("i is 4");
            break;
         default:
             System.out.println("i is greater than 4");
             break;
     }
   } 
   } 

   //switch --> limited use case --> should evaluate to byte, int short, and Enumeration.
   // No duplication cases allowed.
   // After JDK 7 Strings can also be used as switch expression.
   // After JDK 14 switch is enhanced too much.


public class Arithmatic{
    public static void main(String[] args) {
        //Arithmatic operator.
        int a=10;
        int b=40;

        int c=a+b;
        int d=b-a;
        int e=a*b;
        int f=b/a;
        int g=b%a;
        System.out.println(c + "," + d + "," + e + "," + e + "," + f + "," + g);
    }
}
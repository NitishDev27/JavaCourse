public class Relational {
    public static void main(String[] args) {
        // Rerational Operators. --> ==, !=, <, >, <=, >=
        int a=10;
        int b = 10;

        boolean c=(a==b);
        System.out.println(c); // true

        boolean d=(a!=b);
        System.out.println(d); // false

        boolean e = (a<b);
        System.out.println(e); // false

        boolean f=(a<=b);
        System.out.println(f); // true
    }
}
